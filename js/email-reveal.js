/*
 * Press-and-hold email reveal.
 * The address is stored base64-encoded and reversed in the page (data-email),
 * so it never appears as readable text in the HTML. It is decoded only after
 * a real person keeps pressing the button for HOLD_MS milliseconds.
 */
(function () {
    var HOLD_MS = 1000;

    function decode(s) {
        try { return atob(s).split('').reverse().join(''); } catch (e) { return ''; }
    }

    function obfuscate(addr) {
        var parts = addr.split('@');
        return parts[0] + ' (at) ' + parts[1].split('.').join(' (dot) ');
    }

    document.querySelectorAll('.email-reveal').forEach(function (box) {
        var btn = box.querySelector('.hold-btn');
        var out = box.querySelector('.email-revealed');
        var timer = null;

        function reveal() {
            var addr = decode(box.getAttribute('data-email'));
            if (!addr) return;
            out.textContent = obfuscate(addr);
            var copy = document.createElement('button');
            copy.type = 'button';
            copy.className = 'copy-email';
            copy.textContent = 'Copy';
            copy.addEventListener('click', function () {
                if (!navigator.clipboard) return;
                navigator.clipboard.writeText(addr).then(function () {
                    copy.textContent = 'Copied';
                    setTimeout(function () { copy.textContent = 'Copy'; }, 1500);
                });
            });
            out.appendChild(copy);
            btn.remove();
        }

        function start(e) {
            // Ignore events generated by page scripts (a cheap barrier against simple bots).
            if (e && e.isTrusted === false) return;
            if (timer) return;
            btn.classList.add('holding');
            timer = setTimeout(function () { timer = null; reveal(); }, HOLD_MS);
        }

        function cancel() {
            if (timer) { clearTimeout(timer); timer = null; }
            btn.classList.remove('holding');
        }

        btn.addEventListener('pointerdown', function (e) { btn.setPointerCapture && btn.setPointerCapture(e.pointerId); start(e); });
        btn.addEventListener('pointerup', cancel);
        btn.addEventListener('pointercancel', cancel);
        btn.addEventListener('lostpointercapture', cancel);
        btn.addEventListener('contextmenu', function (e) { e.preventDefault(); });
        btn.addEventListener('keydown', function (e) {
            if ((e.key === 'Enter' || e.key === ' ') && !e.repeat) { e.preventDefault(); start(e); }
        });
        btn.addEventListener('keyup', function (e) {
            if (e.key === 'Enter' || e.key === ' ') cancel();
        });
        btn.addEventListener('blur', cancel);
        // A plain click (press shorter than HOLD_MS) does nothing.
        btn.addEventListener('click', function (e) { e.preventDefault(); });
    });
})();
